const execFileAsync = promisify(execFile);

async function git(cwd: string, args: string[]): Promise<string> {
  const { stdout } = await execFileAsync("git", args, { cwd });
  return stdout.trim();
}

async function makeGitRepo(root: string, name: string): Promise<string> {
  const repo = path.join(root, name);
  await fs.mkdir(repo, { recursive: true });
  await git(repo, ["init"]);
  await git(repo, ["config", "user.name", "DevCenter Test"]);
  await git(repo, ["config", "user.email", "devcenter@example.com"]);
  await fs.writeFile(path.join(repo, "README.md"), `# ${name}\n`, "utf8");
  await git(repo, ["add", "README.md"]);
  await git(repo, ["commit", "-m", "init"]);
  return repo;
}

async function makeHome(root: string): Promise<string> {
  return makeGitRepo(root, "Home DevCenter");
}

function withEnv(overrides: Record<string, string | undefined>, run: () => Promise<void>): Promise<void> {
  const saved = new Map<string, string | undefined>();
  for (const key of Object.keys(overrides)) {
    saved.set(key, process.env[key]);
    if (overrides[key] === undefined) {
      delete process.env[key];
    } else {
      process.env[key] = overrides[key];
    }
  }

  return run().finally(() => {
    for (const [key, value] of saved) {
      if (value === undefined) {
        delete process.env[key];
      } else {
        process.env[key] = value;
      }
    }
  });
}

test("deepMerge merges nested objects and replaces arrays and scalars", () => {
  const base = {
    preferred_license: "none",
    branch_naming: { feature: "feature/{slug}", bugfix: "bugfix/{slug}" },
    required_files: ["README.md"],
    pull_requests: { solo_repos: ["optional"] }
  };
  const overlay = {
    preferred_license: "MIT",
    branch_naming: { feature: "feat/{slug}" },
    required_files: ["README.md", "CONTRIBUTING.md"],
    pull_requests: { solo_repos: ["always"] }
  };

  const merged = deepMerge(base, overlay) as Record<string, any>;
  assert.equal(merged.preferred_license, "MIT");
  assert.equal(merged.branch_naming.feature, "feat/{slug}");
  assert.equal(merged.branch_naming.bugfix, "bugfix/{slug}");
  assert.deepEqual(merged.required_files, ["README.md", "CONTRIBUTING.md"]);
  assert.deepEqual(merged.pull_requests.solo_repos, ["always"]);
});

test("DEVCENTER_HOME and the config file drive home resolution", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-home-"));
  const envHome = path.join(root, "env-home");
  const configHome = path.join(root, "config-home");
  await fs.mkdir(envHome, { recursive: true });
  await fs.mkdir(configHome, { recursive: true });
  const configPath = path.join(root, "config.json");
  await fs.writeFile(configPath, JSON.stringify({ home: configHome }), "utf8");

  await withEnv({ DEVCENTER_HOME: envHome, DEVCENTER_CONFIG: configPath }, async () => {
    const resolution = await resolveDevCenterHome();
    assert.equal(resolution.home, envHome);
    assert.equal(resolution.source, "env");
  });

  await withEnv({ DEVCENTER_HOME: undefined, DEVCENTER_CONFIG: configPath }, async () => {
    const resolution = await resolveDevCenterHome();
    assert.equal(resolution.home, configHome);
    assert.equal(resolution.source, "config");
  });

  await withEnv({ DEVCENTER_HOME: undefined, DEVCENTER_CONFIG: path.join(root, "missing.json") }, async () => {
    const resolution = await resolveDevCenterHome();
    assert.equal(resolution.source, "repo");
  });
});

test("materialized standards merge defaults with the home overlay, overlay winning", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-standards-"));
  const home = await makeHome(root);
  await fs.mkdir(path.join(home, "standards"), { recursive: true });
  await fs.writeFile(
    path.join(home, "standards", "global.yaml"),
    "preferred_license: MIT\nbranch_naming:\n  feature: feat/{slug}\n",
    "utf8"
  );
  const sidecarDir = path.join(home, "projects", "Sample", ".devcenter");
  await fs.mkdir(sidecarDir, { recursive: true });

  const outcome = await materializeGlobalStandards(home, sidecarDir);
  assert.equal(outcome.action, "created");

  const snapshot = await fs.readFile(path.join(sidecarDir, "global-standards.yaml"), "utf8");
  assert.match(snapshot, /Generated by devcenter/);
  assert.match(snapshot, /preferred_license: MIT/);
  assert.match(snapshot, /feature: feat\/\{slug\}/);
  // Untouched defaults keys survive the merge.
  assert.match(snapshot, /fix: fix\/\{slug\}/);

  // Re-materializing without source changes is a no-op, so git stays quiet.
  const again = await materializeGlobalStandards(home, sidecarDir);
  assert.equal(again.action, "unchanged");
});

test("materialize replaces a pre-split symlink and refreshAll picks up overlay edits", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-standards-"));
  const home = await makeHome(root);
  await fs.mkdir(path.join(home, "standards"), { recursive: true });
  await fs.writeFile(path.join(home, "standards", "global.yaml"), "preferred_license: none\n", "utf8");
  const sidecarDir = path.join(home, "projects", "Legacy", ".devcenter");
  await fs.mkdir(sidecarDir, { recursive: true });
  await fs.symlink(
    path.join("..", "..", "..", "standards", "global.yaml"),
    path.join(sidecarDir, "global-standards.yaml"),
    "file"
  );

  const outcome = await materializeGlobalStandards(home, sidecarDir);
  assert.equal(outcome.action, "replaced-symlink");
  assert.equal((await fs.lstat(path.join(sidecarDir, "global-standards.yaml"))).isSymbolicLink(), false);

  await fs.writeFile(path.join(home, "standards", "global.yaml"), "preferred_license: MIT\n", "utf8");
  const refreshed = await refreshAllMaterializedStandards(home);
  assert.deepEqual(refreshed, [path.join("projects", "Legacy", ".devcenter", "global-standards.yaml")]);
  const snapshot = await fs.readFile(path.join(sidecarDir, "global-standards.yaml"), "utf8");
  assert.match(snapshot, /preferred_license: MIT/);
});

test("ensure is silent outside git repos and hints for unmanaged repos", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-ensure-"));
  const home = await makeHome(root);

  const plainDir = path.join(root, "not-a-repo");
  await fs.mkdir(plainDir, { recursive: true });
  const silent = await ensureSidecar(plainDir, home);
  assert.equal(silent.exitCode, 0);
  assert.deepEqual(silent.messages, []);

  const project = await makeGitRepo(root, "Unmanaged");
  const hinted = await ensureSidecar(project, home);
  assert.equal(hinted.exitCode, 0);
  assert.match(hinted.messages[0], /not a managed project/);
  assert.match(hinted.messages[0], /devcenter attach/);
  // Hinting must not create memory or links as a side effect.
  await assert.rejects(fs.lstat(path.join(project, "AGENTS.md")), /ENOENT/);
  await assert.rejects(fs.stat(path.join(home, "projects", "Unmanaged")), /ENOENT/);
});

test("ensure restores links for a known project and reports open tasks", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-ensure-"));
  const home = await makeHome(root);
  const project = await makeGitRepo(root, "Known");
  await attachSidecar(project, home);
  await fs.writeFile(
    path.join(home, "projects", "Known", ".devcenter", "tasks.yaml"),
    "- id: K-001\n  title: Open\n  status: next\n- id: K-002\n  title: Closed\n  status: done\n",
    "utf8"
  );

  // Simulate a fresh clone on a second device: memory exists, links do not.
  await fs.unlink(path.join(project, "AGENTS.md"));
  await fs.unlink(path.join(project, "CLAUDE.md"));
  await fs.unlink(path.join(project, ".devcenter"));

  const result = await ensureSidecar(project, home);
  assert.equal(result.exitCode, 0);
  assert.match(result.messages[0], /restored sidecar links/);
  assert.match(result.messages.join("\n"), /1 open task\b/);
  assert.equal((await fs.lstat(path.join(project, "AGENTS.md"))).isSymbolicLink(), true);
  assert.equal((await fs.lstat(path.join(project, ".devcenter"))).isSymbolicLink(), true);

  const settled = await ensureSidecar(project, home);
  assert.equal(settled.messages.some((message) => /restored sidecar links/.test(message)), false);
  assert.match(settled.messages[0], /"Known" attached/);
});

test("ensure prints project standards and context with a pointer to global standards", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-briefing-"));
  const home = await makeHome(root);
  const project = await makeGitRepo(root, "Briefed");
  await attachSidecar(project, home);
  const memory = path.join(home, "projects", "Briefed", ".devcenter");
  await fs.writeFile(path.join(memory, "standards.yaml"), "commits:\n  format: conventional\n", "utf8");
  await fs.writeFile(path.join(memory, "context.md"), "# Briefed Context\n\nShipping the widget API.\n", "utf8");

  const output = (await ensureSidecar(project, home)).messages.join("\n");
  assert.doesNotMatch(output, /auto-load/);
  assert.match(output, /Project standards \(\.devcenter\/standards\.yaml\):\ncommits:\n  format: conventional/);
  assert.match(output, /Project context \(\.devcenter\/context\.md\):\n# Briefed Context\n\nShipping the widget API\./);
  assert.match(output, /Read \.devcenter\/global-standards\.yaml before branching/);
  // The merged global snapshot stays a pointer, not printed content.
  assert.doesNotMatch(output, /Built-in conventions shipped with the devcenter app/);

  // An empty context file drops its section instead of printing a bare header.
  // (A deleted one gets recreated from the template by the attach step.)
  await fs.writeFile(path.join(memory, "context.md"), "\n", "utf8");
  const withoutContext = (await ensureSidecar(project, home)).messages.join("\n");
  assert.doesNotMatch(withoutContext, /Project context/);
  assert.match(withoutContext, /Project standards/);
});

test("ensure truncates an oversized context at a line boundary", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-briefing-cap-"));
  const home = await makeHome(root);
  const project = await makeGitRepo(root, "Verbose");
  await attachSidecar(project, home);
  const line = `${"x".repeat(99)}\n`;
  const context = `# Verbose Context\n${line.repeat(200)}LAST LINE\n`;
  await fs.writeFile(path.join(home, "projects", "Verbose", ".devcenter", "context.md"), context, "utf8");

  const output = (await ensureSidecar(project, home)).messages.join("\n");
  const section = output.slice(output.indexOf("Project context"));
  assert.match(section, /\[truncated at \d+ of \d+ characters; read \.devcenter\/context\.md for the rest\]/);
  assert.doesNotMatch(section, /LAST LINE/);
  const rows = section.split("\n");
  const printed = rows.slice(1, rows.findIndex((row) => row.startsWith("[truncated")));
  assert.equal(printed.every((row) => row === "# Verbose Context" || row === "x".repeat(99)), true);
  assert.ok(printed.join("\n").length <= briefingLimits["context.md"]);
});

test("doctor repoints broken symlinks after the home repo moves", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "devcenter-move-"));
  const home = await makeHome(root);
  const project = await makeGitRepo(root, "Mover");
  await attachSidecar(project, home);

  const movedHome = path.join(root, "Home Renamed");
  await fs.rename(home, movedHome);
  assert.equal((await fs.lstat(path.join(project, "AGENTS.md"))).isSymbolicLink(), true);

  const { doctorSidecar } = await import("./sidecar");
  const result = await doctorSidecar(project, movedHome);
  assert.equal(result.exitCode, 0);
  assert.match(result.messages.join("\n"), /repaired broken/);

  // All three links resolve into the moved home again.
  for (const name of ["AGENTS.md", "CLAUDE.md", ".devcenter"]) {
    const resolved = await fs.realpath(path.join(project, name));
    assert.ok(resolved.startsWith(await fs.realpath(movedHome)), `${name} resolves into the moved home`);
  }
});

